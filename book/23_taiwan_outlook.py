# ### 表三：Båth 與 ETAS
#
# | 量 | 台灣值 | 但書 | 章節 |
# |---|---|---|---|
# | Båth $\Delta_1$（706 序列） | $1.20 \pm 0.73$ | 與 Båth 原值一致，但 $\sigma$ 極大 | 12.5 |
# | Båth（餘震數 > 50） | $0.74 \pm 0.52$ | $\Delta_1$ 隨餘震數下降 | 12.5 |
# | Båth（主震 $M \ge 6$） | $1.26 \pm 0.43$ | 與上一列方向相反，分組決定答案 | 12.5 |
# | Båth（集集，GR 外推） | $\Delta M^* = 0.03$ | 實測 0.95；小餘震異常多 | 12.5 |
