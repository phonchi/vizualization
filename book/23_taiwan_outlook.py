# 注意 Båth 這一組有多亂：1.20、0.74、1.26、0.03、外加一條斜率
# 0.31 的迴歸線。**這種混亂本身就是教學重點**——「常數 1.2」高度
# 依賴序列的餘震數、主震規模門檻與 $M_c$ 的選擇，而 $\sigma = 0.73$
# 意味著 68% 區間橫跨 1.5 個規模單位（能量差約 180 倍），這種區間
# 對疏散決策沒有幫助。
