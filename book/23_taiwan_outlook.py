# 上圖是 M≥5 的大事件——集集與 0403 花蓮的餘震序列像兩根
# 直柱。下圖的年事件數同時寫著兩部歷史：1999 與 2024 的兩根
# 尖峰是餘震序列，來自地球；1994 年那次翻倍的階梯（觸發式改
# 連續記錄）則來自儀器。至於 2012 年的觀測網升級，增加的主要
# 是 M2 以下的微震偵測，在這份 M≥2 的公開目錄裡幾乎看不出來。
# 第 11 章的功課在自己的資料上一目瞭然：讀任何目錄統計圖，先問
# 哪些特徵來自地球、哪些來自儀器。
#
# 幾件家底值得清點。規模尺度經歷兩次大換代（震度反推的 $M_H$ →
# 延時規模 $M_D$ → 1991 年起模擬 Wood–Anderson 的 $M_L$，
# 其間 1987 年 $M_D$ 另有一次類比轉數位），
# 學界已把 1900–2014 的目錄均一化成 $M_w$（Chang et al. 2016，
# 補回 188 個早年事件、修復 1985–1991 的資料空隙）；寬頻矩
# 張量目錄 AutoBATS 提供 1996 年以來八千多個自動機制解，並
# 給出台灣的規模轉換式 $M_w = 0.87\,M_L + 0.23$——$M_L$ 在
# 大規模端飽和偏高，做任何跨目錄比較前先換算。中央氣象署的地震目錄全期累積超過 67 萬筆（含更早年代與大量
# 微小規模事件；本章使用的 1973 年起、M≥2 公開目錄約 35 萬筆），
# 是這一切的基石。
