# 另外一條要單獨列，因為它顛覆的是教科書講法：Tsai et al. (2012)
# 用台灣目錄檢驗多碎形應力活化模型的預測，得到
#
# $$p(M_m) = (0.11 \pm 0.01)\,M_m + (0.38 \pm 0.02),$$
