# 這張圖是本章第一個要記住的機制：**權重不是人訂的，是資料決定
# 的**。序列剛發生時，系統對它一無所知，只能借用整個區域的平均
# 行為；隨著餘震進來，這個序列自己的個性逐漸把通用先驗擠開。這
# 與下一節美國系統的貝氏設計是同一件事的兩種寫法——一個用模型
# 權重表達，一個用後驗分布表達。
#
# ### primary 與 secondary：誰是誰的餘震
#
# STEP 把事件分成兩類。**primary** 是序列的母事件；**secondary**
# 則是某個前序事件的餘震——而那個前序事件本身不必是 primary。
# 連結的規則有兩條：餘震透過時空定義的「餘震區」歸屬到母事件，
# 而且一個事件**只能是規模相等或更大事件的餘震**。
#
# 這個區分有一個很實際的後果：**序列自身擬合的參數只用在 primary
# 事件的餘震率上，secondary 一律回到通用參數**。理由是資料量——
# 一個 secondary 事件自己的後代通常少到不夠擬合，硬要擬合只會得到
# 一組被雜訊主宰的參數。這是作業化系統裡反覆出現的取捨：**能不能
# 估**，跟**該不該估**，是兩個問題。
#
# ### 為什麼是「取最大」而不是相加
#
# 單一元件之內，某個位置的預報率取「所有前序 primary／secondary
# 事件在該位置預報的餘震率的**最大值**」，而不是把它們加起來。
# 這個規則叫 **Avmax**，後來被紐西蘭的混成危害模型整套沿用。
#
# 理由值得停下來想清楚，因為它是全章最容易搞混的一點。判準只有
# 一句話：**兩個率描述的是同一群事件，還是不同群事件**。
#
# - 同一個位置附近的多個母事件，各自的餘震區重疊——它們**對同一
#   塊地的同一批未來地震給出彼此競爭的估計**。相加等於重複計數，
#   所以取最大（取包絡）。
# - 時變叢集項與時間獨立背景項則不同：背景項描述的是「不屬於任何
#   已知序列的地震」，叢集項描述的是「被已知事件觸發的地震」。
#   兩者是**互斥的事件來源**，所以 STEP 對它們是**相加**。
#
# 同一章裡同時出現取最大與相加，不是不一致，是因為判準本來就在
# 「同一群 vs 不同群」上。附錄把這件事寫成兩行不等式。
#
# 時變項疊在時間獨立背景項上，還帶來一個結構性的好處：背景項通常
# **直接接國家地震危害模型**（去叢集後的目錄平滑而得），因此當序列
# 衰減完畢、時變項歸零，整張地圖會自動退回長期危害模型。短期預報
# 與長期危害**天然一致**，不必事後對帳。這正是 21.5 節時變危害那條
# 曲線「整條上移、再整條落回」的模型端來源。
#
# ### STEP 與 ETAS 的取捨
#
# | 面向 | STEP | ETAS |
# |---|---|---|
# | 計算 | 解析、便宜 | 未來事件的後代須模擬（萬次量級） |
# | 二次觸發 | **部分**納入（靠 secondary 機制） | **完整**遞迴 |
# | 架構 | 多元件組合，易與 NSHM 整合 | 自洽的單一模型 |
# | 彈性 | 可換空間核、可吃有限斷層輸入 | 核形式較固定 |
#
# 這張表沒有贏家。ETAS 在統計上更誠實
# （{doc}`第 13 章 <13_etas_structure>`的世代分解說明了為什麼
# 二次觸發不能省），STEP 在工程上更好養（第 4 步的成本取捨，
# 見 22.1 節）。義大利兩個都用，讓
# 集成的權重去決定；美國兩個都有，境內用便宜的、境外用貴的。
#
# ## 22.3 三國系統完整對照
#
# 二十年下來，世界上長出三種代表性的作業化路線。
# {doc}`第 9 章 <09_forecasting_intro>`把這場對照留給了本章，因為
# 它要說的重點需要工程細節撐著才成立——三個系統算機率的能力相近，
# 差異幾乎全在**制度與資料**，不在模型。
#
# | 面向 | 義大利 INGV | 紐西蘭 GNS/GeoNet | 美國 USGS |
# |---|---|---|---|
# | 引擎 | ETAS＋ETES＋STEP 集成 | 短期 STEP/ETAS、中期 EEPAS、長期 PPE | 境內 R–J 貝氏；境外 ETAS |
# | 組合方式 | 依表現加權，**每週更新權重** | **Avmax** 逐點取最大 | 單一引擎，無集成 |
# | 空間解析 | 0.1°×0.1°（排除火山區） | CSEP 紐西蘭測試區 | 事件頁；境外版可出圖 |
#
# | 面向 | 義大利 INGV | 紐西蘭 GNS/GeoNet | 美國 USGS |
# |---|---|---|---|
# | 節奏 | 每日午夜＋每個 $M_L\ge3.5$ 之後，發布未來一週 | **無固定排程**，隨序列演化 | 大震後自動首報，之後按排程更新 |
# | 公開 | **不對大眾公開**（民防、地方政府） | **完全公開**（網站＋社群媒體） | **完全公開**（事件頁） |
# | 把關／痛點 | 候選模型**必須提交過 CSEP** | 目錄異質性；不預報 $M<5.0$ | 只貝氏更新生產力參數 |
#
# 三個系統各有一個值得單獨記住的細節。
#
# ### 義大利：把第三方檢驗寫進制度
#
# 嚴格按 Jordan et al.（2011）的定義，全世界**只有義大利**算完整
# 部署了 OEF：2013 年建立、每週產出預報、還含損失預報（OELF）。
# 它同時是最保守的——至今僅授權人員與民防體系可存取，近年才釋出
# 給地方政府討論如何運用。
#
# 最值得抄的是那條把關規則：**候選模型要加入官方集成，唯一的強制
# 條件是必須提交過 CSEP 實驗接受獨立透明的評估**。第 18 章那句
# 「開發者自己相信不算證據」，在義大利不是一句學術修辭，而是一道
# 行政門檻。另外兩個工程細節也值得知道：全程只用 $M_L$（明知它會
# 飽和，但為了目錄一致仍然只用它）；序列進行中**不更新生產力**，
# 模型在 2005–2009 的學習期校準完就固定。
#
# ### 紐西蘭：公開，以及目錄留下的疤
#
# 紐西蘭自 2010 年 M7.1 Darfield 地震起就對公眾發布預報，三個時間
# 尺度分工清楚：短期（時到週）是大震後的時間叢集，用 STEP、ETAS；
# 中期（月到年）是大震前的地震活動增加，用 EEPAS（第 16 章）；長期
# （數十年）是空間叢集，用 PPE 與國家危害模型背景。三者以 Avmax
# 混成。
#
# 它的痛點是**目錄**。2012 年換了處理系統、規模尺標跟著偏移，導致
# 模型參數至今仍停在 2012 年之前的資料上，而且系統**不願預報
# $M<5.0$**——因為小規模端的目錄異質性已經大到讓參數不可信。這對
# 任何有長期目錄異質性問題的地區（包括台灣）都是直接的警示：**你
# 的模型能預報到多小的規模，是你的觀測網歷史決定的，不是你的統計
# 方法決定的**。
#
# ### 美國：貝氏更新的具體化
#
# 美國境內是自動的 R–J 貝氏解，境外則由分析員人工啟動 ETAS 並跑
# 上萬次隨機事件集。境內系統的設計是「貝氏更新」最好的教材：
# $t=0$ 時沒有任何本序列的資料，先驗是一個**涵蓋過去序列行為範圍**
# 的通用分布，因此預報**最寬**；隨著餘震進來，後驗逐步收斂到這個
# 序列自己的行為。**不確定性帶隨時間變窄，本身就是資訊**。
#
# 兩個誠實的細節。其一，目前只對**生產力參數**做貝氏更新，$c$
# 與 $p$ 固定在通用點估計，直到分析員判斷序列明顯偏離才放開——
# 三個參數只放開一個並不難理解：第 12 章的 12.3 節示範過，同一個
# 序列只要改變擬合窗長，$\hat p$ 就能從 0.9 走到 1.5 再崩到 0.7，
# 序列早期尤其如此。既然短窗估不穩，不如先釘住它，把資料留給最
# 有訊息的那個參數。通用模型則依構造環境分成十幾種，等於把「這是什麼
# 樣的地方」也編進先驗裡。其二，境內外系統**都不含背景地震活動
# 的預報**，只算餘震；在活躍地區、序列後期，這會低估真實危害。
# 順帶一提，「大震後約 20 分鐘自動發出首報」這個常被引用的數字，
# 出處是 Mizrahi et al.（2024）的回顧，不是一份系統規格書。
#
# 用合成資料把貝氏機制畫出來——先驗均值設在通用值，但這個序列
# 真實的生產力只有通用值的六成：

# %% tags=["hide-input"]
A_GEN, C_OM, P_OM = 30.0, 0.05, 1.08     # 通用參數下的餘震生產力（合成）
THETA_TRUE = 0.60                        # 本序列真實的生產力倍數
ALPHA0, BETA0 = 2.0, 2.0                 # 通用先驗 Gamma：均值 1、很寬

EDGES = np.array([0.0, 0.25, 0.5, 1.0, 3.0, 7.0, 30.0])
E_j = np.array([quad(lambda t: A_GEN * (t + C_OM) ** -P_OM, a, b)[0]
                for a, b in zip(EDGES[:-1], EDGES[1:])])
n_j = rng.poisson(THETA_TRUE * E_j)                    # 逐段觀測到的餘震數
