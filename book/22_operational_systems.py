# 讀法有三層。**第一層**：藍色的先驗又寬又平，它老實承認「我對這
# 個序列一無所知，只知道歷史上的序列大致落在這個範圍」。**第二
# 層**：第一天結束時後驗已經收窄一大截，因為 Omori 律讓絕大多數
# 餘震擠在最初幾天——早期資料的資訊密度最高。**第三層**：後驗中心
# 從 1.0 一路移向 0.6，也就是系統逐漸發現「這個序列比通用值安靜」。
#
# 如果在第一天就照通用先驗發布，機率會系統性偏高。這不是理論上的
# 擔憂——下一節就是它真實發生的樣子。
#
# ## 22.4 上線後怎麼壞
#
# 2016 年紐西蘭 Kaikōura $M_w$ 7.8 是作業化系統最好的實戰教案，
# 因為它壞得非常典型。
#
# 序列初期，完整規模的估計出了問題。大震之後的頭幾小時到幾天，
# 小地震的波形被大地震與彼此的尾波淹沒，目錄的 $M_c$ 會急遽上升
# 再緩慢回落（{doc}`第 11 章 <11_catalog_completeness_b>`）。
# Kaikōura 的自動估計沒能追上這個變化，$M_c$ 被固定在 3.95。門檻
# 一旦定死在高處，可用來擬合的餘震數就湊不到 100 個，第 22.2 節那
# 個切換機制便**卡在第一層**——系統只能一直用區域通用參數。
#
# 結果是：**通用預報高估了實際觀測到的餘震數**。
#
# 把責任歸位很重要。錯誤的源頭**不在模型公式**——R–J 與 STEP 的
# 數學一行都沒錯；也不在參數估計法——沒有資料，估計法再好也無米
# 可炊。源頭在**資料的即時品質**。第 14 章的 14.6 節已經證明過這
# 條因果鏈：不完整性會直接污染參數估計，$M_c$ 設錯會讓 $p$、$K$
# 系統性偏移。作業化系統只是把那個實驗室結論搬到了真實世界，並且
# 加上一個新的維度——**時間壓力**。研究時你可以等三個月，用重定位
# 過的目錄慢慢重估 $M_c$；作業系統必須在事件發生後幾分鐘內，用
# 一份還在滾動、還在補資料、還在改規模的即時目錄做決定。
#
# 這個落差本身就該寫進系統的風險清單。即時目錄與研究目錄的差別
# 不只是「精度差一點」：定位可能偏移數公里、規模可能差 0.2–0.3、
# 小事件會在數小時後被補進來（於是昨天的率被今天改寫）、偶爾還
# 會有非地震訊號混入。第 23 章會看到台灣的作業紀錄裡有同樣的
# 誠實記載——某段「平靜」無法僅憑即時目錄下定論。
#
# **作業化系統的風險清單上，資料永遠排在模型前面**。
#
# ## 22.5 L'Aquila 與 ICEF
#
# 2009 年 4 月 6 日，義大利 L'Aquila 發生 $M_w$ 6.3 地震，約三百人
# 罹難。震前該區有持續數月的群震，官方留給公眾的訊息卻被廣泛理解
# 為「不會有大地震」。
#
# 後續的審判讓全世界的地震學家記住了一課。但這一課經常被記錯——
# 記成「說了會被告，所以最好不要說」。真相是雙面的：
#
# ```{admonition} L'Aquila 的兩面教訓
# :class: warning
# **一面**是說錯話的法律風險：科學家與官員因發布的訊息被追究責任，
# 這讓整個社群此後對「要不要公開講機率」變得緊張。
# **另一面**卻方向相反：他們被批評的內容，恰恰是**沒有把「機率
# 確實升高了」講得夠清楚、夠強**。沉默的代價與說錯話的代價同樣
# 真實。只學到前一面的人，會得出「閉嘴最安全」這個完全錯誤的
# 結論。
# ```
#
# 這場災難直接催生了 **ICEF**（International Commission for
# Earthquake Forecasting）與「作業化地震預報」這個領域
# （Jordan et al. 2011）。ICEF 的建議可以濃縮成一句：**與其在
# 「能不能預測」上空轉、臨場即興發言，不如建立常態化、權威、
# 透明的機率發布制度**。
#
# 第 9 章給過 OEF 的定義，這裡補上它的來歷與代價。兩個關鍵詞值得
# 再看一次。**作業化（operational）**借自氣象學，指模型有自動、
# 及時的應用，因而資訊的「可行動性」提高。**權威（authoritative）**
# 是更硬的限定：資訊必須來自官方、可信、且**依法負有提供該資訊
# 之責**的來源。
#
# 這裡有一句話值得撐起一整節課：**權威性不能自我宣稱**。它必須由
# 更高層級（通常是政府）授予。一個研究團隊可以做出全世界最好的
# 模型、跑在最穩的機器上、通過所有 CSEP 檢驗，然後發現自己仍然
# 不能發布——因為第 5 步不在科學的管轄範圍內。這正是第 22.1 節
# 那道斷層最赤裸的樣子。
#
# ## 22.6 機率溝通是有實驗的科學
#
# 理工背景的讀者有一個很頑固的預設：**算出機率是科學，怎麼講是
# 公關**。這一節的目的就是拆掉它。機率溝通有假說、有對照實驗、
# 有可測量的結果變數——它是科學，而且是本章裡實驗證據最紮實的
# 一部分。
#
# ### 框架效應：一個介系詞就能改變理解
#
# 說「在未來一週**之內**（within the next week）」與說「在下一週
# （in the next week）」，人們的推論不一樣：後者會讓相當比例的
# 受訪者以為事件將發生在**時窗的末端**（Doyle et al. 2020）。這是
# 可以設計實驗測出來的效應，不是文案品味。
#
# 更有效的做法是**換一個參照系**。Dryhurst et al.（2022）以跨國
# 實驗測試了多種表述，找出一個明顯改善理解的頻率框架：
#
# > 想像有 100,000 個地震機率與此地完全相同的地方。在這一週，
# > 我們預期其中 y 個地方會發生……、z 個地方不會發生……
#
# 把抽象的百分比翻譯成可數的地方數量，人的直覺就接得上了。用
# Kaikōura 的真實預報數字把這個框架畫出來——每個點代表 1,000 個
# 「機率與此地相同」的地方：

