# ## 22.7 專家共識與歧異（Delphi）
#
# 上面這些「應該怎麼做」的判斷，並不是某個人的意見。Mizrahi et
# al.（2024）的回顧用 **Delphi 法**對 20 位國際專家做了正式的意見
# 徵集——匿名、多輪、每輪回饋群體結果讓專家有機會修正——目的是
# 分辨哪些是社群共識、哪些其實還在吵。
#
# **有共識的部分**：
#
# - **模型要納入高階餘震**（餘震的餘震）——這是唯一不分使用者
#   群體都被認為重要的模型成分，也是 STEP 相對 ETAS 的已知弱點。
# - **ETAS 應作為預設／基準模型**，並鼓勵使用集成。
# - 檢驗必須**與基準模型比較**、必須是**前瞻或擬前瞻**、且應有
#   **第三方參與**（例如 CSEP 實驗）。
# - 「**開發者自己相信模型**」被明確判定為**不足夠**；模型可以
#   更新參數，但**換一個區域必須重新檢驗**。
# - 溝通產品**必須與使用者群體協同開發**——這是全部題目中共識
#   最強的一條。
#
# 有一條共識則值得加註警語：專家目前**不認為** $b$ 值的時空變化
# 或大地測量資訊是重要的模型成分。回顧作者自己提醒，這只反映
# **當下的研究狀態**——22.11 節要談的 FTLS 正是拿 $b$ 值時變做
# 判別，而近年也有用大地測量訊號做前兆的嘗試。專家共識是一張
# 快照，不是一條定律；把它當成研究方向的禁令，就誤讀了 Delphi
# 這個方法。
#
# **沒有共識的部分**只有一條，但它是最關鍵的一條：**訂不出一組
# 「模型上線前必須通過」的最低檢驗集**。
#
# 為什麼訂不出來？回顧的分析很精采，因為分歧不在技術而在目的：
#
# - **科學導向**的視角認為，應該有辦法確定性地淘汰太差的模型；
#   檢驗的功能是**把關**。
# - **使用者導向**的視角則認為，該依用途決定檢驗方式，甚至願意
#   使用未經完整檢驗的模型——理由是：**如果替代方案是完全不給
#   資訊，那麼即使簡單如 R–J 也能改善決策**。
#
# 兩種立場都不荒謬，而且無法用更多資料調解，因為它們對「檢驗是
# 為了什麼」有不同的答案。這是本章第二個「瓶頸不在統計」的例證。
#
# 還有一個很有意思的後設觀察：**專家在「溝通」議題上的共識，反而
# 比在「模型開發與檢驗」上高**。回顧作者的推測相當坦率——正因為
# 專家在溝通領域的經驗較少；在自己最專精的領域，每個人都堅持
# 自己的觀點。
#
# ## 22.8 沒有模型時怎麼辦：慢滑移與專家徵詢
#
# Kaikōura 主震後第 10 天，GPS 資料顯示 Hikurangi 隱沒帶邊緣出現
# **廣泛的慢滑移事件（SSE）**。這件事立刻帶來一個作業上的問題：
# 慢滑移會不會提高後續大地震的機率？提高多少？
#
# 問題在於，當時幾乎**沒有現成的研究可以依循**，更沒有任何一個
# 可以插上電就跑的模型。這正是作業化系統在真實世界裡最常遇到、
# 教科書卻最少討論的處境：**你需要一個數字，但沒有模型**。
#
# GNS 的作法是**非結構化的專家徵詢**：請每一位專家獨立給出「未來
# 一年內中紐西蘭 $M\ge7.8$ 的機率」的最佳估計與 90% 信賴界限，再
# 把結果平均。得到的答案是 **5%（2%–8%）**。
#
# 這是全世界第一次為慢滑移事件做這種建模演練，值得記住的不是那個
# 5%，而是方法論上的一句話：**當模型不存在時，結構化（或至少有
# 紀律的）專家判斷本身就是方法**，不是打混。它可以被記錄、被
# 覆核、被事後檢驗，也可以誠實地把不確定性寫成一個區間。同樣的
# 邏輯在第 20 章出現過——複發模型的 logic tree 權重也來自專家
# 判斷；紐西蘭 Canterbury 的時變危害模型更進一步，用<strong>結構化
# 專家判斷（Cooke 古典模型）</strong>決定各模型的權重。差別只在於，那些
# 場合是為了選權重，這裡是為了憑空生出一個機率。
#
# 反過來說，它的極限也很清楚：專家徵詢**無法被前瞻檢驗**（一次性
# 事件，沒有樣本），也無法保證下一次徵詢會得到相同答案。它是
# 沒有模型時的臨時橋樑，不是模型的替代品。
#
# ## 22.9 倫理與開放科學
#
# 走到這裡，「這個模型該不該公開」已經不再是技術問題。地震學社群
# 近年把它明確地當成**倫理**問題來討論（Dallo et al. 2023），並且
# 分成兩層：
#
# - **內部研究倫理**：資料保護、FAIR 原則、利益衝突、以及「產出
#   開放科學」本身的義務。
# - **外部研究倫理**：資訊誤用、對社會的責任、法律後果（L'Aquila
#   訴訟被直接點名）、包容的研究文化。
#
# 外部倫理有兩個具體的風險特別值得放在心上。其一，**開放的地震
# 預報模型可能被誤解或誤用**，進而降低社會對模型的信任；其二，
# 更糟的是它可能被**刻意操弄以產生誇大的預報**，造成恐慌。開放
# 從來不是零成本的。
#
# 而開放的理由同樣硬。可重現性在這個領域不只是技術規範，而是
# **倫理義務**——因為你的模型會影響別人的生命決策，所以你有義務
# 公開它，也有義務思考它被誤用的後果。實踐上的三件工具：
# **可重現性套件**（程式碼＋資料＋執行環境，讓人不必額外努力就能
# 重現結果）、**FAIR 原則**（可尋、可取、可互通、可再用），以及
# **pyCSEP**（開源的預報檢驗工具箱，讓人不必自己重造第 17、18 章
# 那整套檢驗架構）。
#
# 這裡與第 14 章接得非常緊。14.11 節指出，社群**缺一個真正標準化
# 的 ETAS 基準版本**——沒有兩個 ETAS 實作是相同的，於是「贏過
# ETAS」這句話沒有明確意義。這正是「開放科學不只是道德訴求，而是
# **科學進展的必要條件**」的最強論證：不能重現，就不能比較；不能
# 比較，這個領域就沒有淘汰機制。
#
# 最後是一個很少被寫進教科書的場景。那不勒斯的工作坊實際辯論過
# 「能不能就這樣把短期機率預報公開」，並且**投票**——多數支持
# 無條件公開，理由是「有些資訊對個人決策而言比沒有資訊更有用」
# （與 22.7 節使用者導向的立場如出一轍）。但作者立刻補上兩句
# 限制。第一句我們已經見過：人們要的是可行動的資訊，不是機率。
# 第二句更尖銳：**用民主方式建立共識，這件事本身可能是不倫理
# 的**，因為在投票的房間裡，少數群體往往未被充分代表。
#
# 一個判準若連自己的正當性都要接受檢查，那大概是這個領域成熟的
# 徵兆。
#
# ## 22.10 常見誤解與陷阱
#
# **誤解 1：「STEP 就是 USGS 現在在跑的系統。」** 不是。2005 年
# 上線的 STEP 即時系統早已走入歷史，美國現行的是**作業化餘震預報
# （OAF）**，引擎是 R–J 或 ETAS，參數有通用、序列特定、貝氏結合
# 三種來源。這是很常見的世代誤植。附帶一提，紐西蘭的混成模型倒是
# 真的還在用 STEP 當短期元件之一——同一個名字在不同國家的現況
# 不同。
#
# **誤解 2：「機率增益幾十倍，所以現在很危險。」** 增益大不等於
# 絕對機率高。第 14 章那條衰減曲線已經說得很清楚：主震剛過時
# 「一週內再來一個更大的」相對背景可以高上百倍，絕對值卻始終是
# 個位數到幾十個百分比。Kaikōura 的 $M\ge7$ 是 5%——比平時高了
# 幾個數量級，同時也是「二十次裡有十九次不會發生」。**兩句話都
# 要說，只說一句就是誤導**，而且是兩個方向的誤導。
#
# **誤解 3：「取最大就是集成。」** 不是。Avmax 是**逐點取包絡**，
# 它不守恆——合成後的總期望事件數會**大於**任何單一模型
# （附錄有兩行證明）。第 19 章的凸組合則守恆，而且只有加權平均
# 型的集成能藉由單一預報之間的離散度提供**認知不確定性**的資訊。
# Avmax 是刻意保守的工程選擇，不是統計上的模型平均。
#
# **誤解 4：「作業化系統的難點是模型精度。」** 本章從頭到尾都在
# 反駁這一條。Kaikōura 壞在 $M_c$ 估計（資料）；義大利不公開
# （制度）；紐西蘭不預報 $M<5.0$（目錄歷史）；三情境為什麼要那樣
# 寫（社會科學）。模型公式在這些故事裡一行都沒錯。
#
# **誤解 5：「餘震預報只在震後幾天有意義。」** Canterbury 序列
# 第六年的 M5.7 造成實質損害，並把年機率從 50% 推到 63%。Omori
# 律是冪次衰減——它的尾巴長到會出現在**行政與保險的時間尺度**上，
# 不只是新聞週期。
#
# **誤解 6：「義大利有 OEF，所以義大利民眾看得到機率。」** 恰恰
# 相反。全世界唯一完整部署 OEF 的國家，是三國中**唯一不對大眾
# 公開**的。「有系統」與「有公開的資訊服務」是兩件事。
#
# ## 22.11 研究前沿與未解問題
#
# **前震紅綠燈要上線還缺什麼。** FTLS（Foreshock Traffic Light
# System, Gulia & Wiemer 2019）追蹤大震後 $b$ 值的時變，作為
# 「這是正常餘震序列，還是更大事件的前震序列」的一階判別：若
# $b$ 值不升反降，燈號轉紅。原理有實驗室與野外支持，但要上線還
# 缺兩件事。第一，$b$ 值估計本身有多種偏差來源（$M_c$、規模
# 尺標、樣本數——第 11 章整章都在講這件事），而 FTLS 恰恰用在
# $M_c$ 最不穩定的時段。第二，也是更根本的：**顏色警示不是機率
# 預報**，無法直接與 ETAS 或 STEP 做第 18 章那種資訊增益比較。
# 在轉換成機率之前，它不能進入集成，也不能被同一套標準檢驗。
#
# **機器學習從卻步到重返。** 第 14 章的 14.11 節記錄了完整的故事
# 弧：DeVries et al.（2018）的深度學習餘震預測被 Mignan &
# Broccardo（2019）證明與遠更簡單的模型資訊量相當，社群一度卻
# 步；近年 FERN 與神經點過程在資料充足時已能匹敵或略勝 ETAS，
# 而且**對目錄的非平穩性極為適應**——這正好對應本章 22.4 節的
# 痛點。真正的作業化考驗還在後面：它要能在半夜自動跑、在目錄
# 正在滾動時輸出、並且說得出自己為什麼給這個數字。
#
# **衝擊型預報（impact-based forecasting）。** 從「地震發生機率」
# 走向「後果機率」——氣象服務的經驗顯示，提供衝擊資訊**能改善
# 風險感知，但不必然轉化為行動**。障礙是資料：缺乏衝擊資料、
# 需要理解受影響人群的易損性與應變能力，還要決定產品是為個人
# 還是社群尺度設計。
#
# **OELF：把預報接到損失。** 這是第 21 章那條鏈的終點——義大利的
# 原型引擎每日接收全國地震率，配合建物清冊與易損性模型，換算成
# 預期的不可使用建物數、倒塌數與傷亡人數。紐西蘭的版本更貼近
# 工程決策：Canterbury 重建的時變危害模型，以及 Kaikōura 之後
# 支撐無筋磚造建築強制補強決策的機率增益計算。這條路上的每一步
# 都在增加需要的資料種類，也在增加被質疑的表面積。
#
# **一個共同的天花板。** 所有現行作業化模型都是**叢集模型**，
# 因此都**無法以高機率預報未來的大地震**。它們的強項是餘震，不是
# 大地震。凡是宣稱能預報大地震的系統，先問它有沒有通過前瞻檢驗
# 與基準比較。
#
# **台灣的制度選擇題。** 技術零件在台灣其實已經齊備（第 13、14
# 章的 ETAS 在地化與作業化快報）。剩下的是兩個非技術問題：機率
# 預報的**權威性由誰授予**？要走義大利路線（權威但不公開、先服務
# 民防）、紐西蘭路線（公開、與使用者共同設計）、還是美國路線
# （只在大震後自動發布）？這題留給
# {doc}`第 23 章 <23_taiwan_outlook>`正面回答。
#
# ## 22.12 附錄：Avmax 與相加的形式化比較
#
# 22.2 節說 STEP 在一個地方取最大、在另一個地方相加。把它寫成
# 兩行就不會再混淆。
#
# **情況一：不同來源。** 設背景過程與觸發過程互不重疊地產生事件，
# 率分別為 $\lambda_{\rm bg}$ 與 $\lambda_{\rm cl}$。獨立 Poisson
# 過程的疊加仍是 Poisson，率相加：
#
# $$\lambda(x) = \lambda_{\rm bg}(x) + \lambda_{\rm cl}(x),
#   \qquad \Lambda = \Lambda_{\rm bg} + \Lambda_{\rm cl} .$$
#
# 這是正確的，因為兩者描述的是**互斥的事件族群**。
#
# **情況二：同一族群的多個估計。** 設 $\lambda_1,\dots,\lambda_K$
# 都試圖描述**同一批**未來事件（例如多個母事件重疊的餘震區）。
# 若各自無偏，相加會得到
# $\mathbb{E}[N] \approx K\,\mathbb{E}[N_{\rm true}]$——重複計數。
# 可行的合成有兩類——第 19 章的凸組合，以及 Avmax：
#
# $$\begin{aligned}
# \lambda_\pi(x) &= \sum_i \pi_i \lambda_i(x),
#    \qquad \textstyle\sum_i \pi_i = 1 ,\\
# \lambda_{\max}(x) &= \max_i \lambda_i(x) .
# \end{aligned}$$
#
# 兩者的性質差很多。凸組合**守恆**：
# $\Lambda_\pi = \sum_i \pi_i \Lambda_i$，總期望數落在各模型之間。
# Avmax 則對每一點都滿足 $\lambda_{\max} \ge \lambda_i$，積分後
#
# $$\Lambda_{\max} \;\ge\; \max_i \Lambda_i \;\ge\;
#   \sum_i \pi_i \Lambda_i = \Lambda_\pi ,$$
#
# 第一個等號只在某一個 $\lambda_i$ **逐點支配**其他模型時成立。
# 換句話說，只要兩個模型的空間分布有交錯（實務上總是如此），
# **Avmax 就會膨脹總期望事件數**。
#
# 這不是 bug，是設計。取最大等於在每一點採信最悲觀的那個模型，
# 是一個明確的保守選擇，適合危害度與工程決策的脈絡。但它的代價
# 要說清楚：$\Lambda_{\max}$ 會系統性地高於任何單一模型，因此
# 用第 17 章的 N 檢驗去驗它，**幾乎注定會被判定高估**；而且它
# 沒有權重，也就給不出第 19 章那個副產品——模型之間的離散度所
# 承載的認知不確定性。
#
# 一句話總結：**判準是「同一群還是不同群」，不是「保守還是不
# 保守」**；先分清族群，再決定要不要保守。
