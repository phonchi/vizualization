# 三張點陣圖來自**同一份預報**。左邊幾乎全滿，右邊只有五個點——
# 一份預報內部就跨了兩個數量級。這是「機率量級感」最有效的一張
# 圖：不需要任何統計訓練，也能一眼看出 98% 和 5% 是完全不同性質
# 的訊息。
#
# 順帶一個值得盯著看的算術。這三個規模帶同時公布了平均個數
# 5.6、0.53、0.05。若假設 Poisson，$P=1-e^{-\Lambda}$ 給出 41.1%
# 與 4.9%——與公布的 41% 與 5% **完全吻合**；但 5.6 個算出來是
# 99.6%，公布值卻是 98%。這不是筆誤，而是
# {doc}`第 17 章 <17_testing_consistency>`負二項那一節的徵狀：
# 當率夠高時，序列之間的變異（過度離散）會讓「至少一次」的機率
# **低於**同均值的 Poisson 值；率很低時這個效應是二階小量，所以
# 另外兩帶看不出來。**同一張表裡，兩種分布假設的差異剛好在最上面
# 那一格露出來**。
#
# ### 數量範圍比機率範圍抗扭曲
#
# 給不確定性範圍時有個兩難：有人只想要一個數字前面加「大約」，
# 有人想知道均值周圍的散布。但實務上有一個**可實證比較**的性質：
# 媒體轉述**機率區間**時幾乎只報最悲觀的上限；而轉述「預期地震
# **數量**的範圍」（例如 0–2 個）卻相對忠實——2018 年阿拉斯加
# M7.1 之後的經驗即是如此。
#
# 這條啟示很便宜也很有用：**同樣的不確定性，換一個載體，抗扭曲
# 能力就不一樣**。GeoNet 的預報表因此每一格同時給三個東西——平均
# 預期個數、可能範圍、至少發生一次的機率——再配上文字判讀語彙，
# 例如「29% 的機率（**unlikely**）」、「小於 1%（**extremely
# unlikely**）」。數字給專業者，文字給所有人，範圍給媒體。
#
# ### 另外四條可操作的建議
#
# 這一節的每一條都來自實務評估或專家共識，而且都可以被抄。
#
# - **把「已過期間的預報數」與「實際觀測數」並列**。看得到自己
#   上一次說了什麼、後來真的發生了什麼，收訊者對預報準確性會
#   安心得多（Becker et al. 2019）。這其實是把第 17 章的 N 檢驗
#   從論文搬到公開網頁上——只是讀者是民眾。
# - **分層提供資訊**。讓使用者自取所需的深度：最外層是一句
#   非技術的訊息（例如「為更多地震做準備」），願意讀下去的人
#   才進入表格、參數與方法說明。美國的事件頁就是這個結構——
#   摘要、評註、預報表、模型參數四個分頁。
# - **同理心訊息搭配整備建議**。純資訊的發布會讓收訊者停在焦慮
#   上；接上「所以現在可以做什麼」才有出口。
# - **常態化發布，而不是只在壞消息時出現**。只有壞消息才發言的
#   機構，發言本身就變成了警報。
#
# 反過來，已經被辨識出來的溝通挑戰也有一張清單：預報會造成焦慮、
# 會影響觀光等產業；專業者與大眾都難以把機率轉成行動；大眾傾向
# 拿地震預報類比天氣預報（因而期待精確的時間地點）；大震沒有造成
# 明顯損害會產生**常態化偏誤**；以及最根本的一條——**人們想理解
# 不確定性，而我們還不知道怎麼有意義地傳達它**。
#
