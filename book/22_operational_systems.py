# # 22. 作業化系統：STEP、OEF 與機率溝通
#
# {doc}`上一章 <21_psha>`把預報接到了危害度：短期地震率餵進 PSHA
# 的積分，就得到會隨序列演化的地動超越機率。那是整條鏈的**輸出
# 端**。這一章往回走，看這條鏈的**中段**——一個統計模型要變成
# 一台 24 小時運轉、對社會發布數字的機器，中間要補上哪些東西。
#
# 引擎我們早就看過了。{doc}`第 14 章 <14_etas_estimation>`的 14.7
# 節從 ETAS 推出 Reasenberg–Jones 的解析特例 {eq}`eq:rj-rate`，
# 並列出加州通用參數、加州實測前震率、日本參數三者的對照——同一
# 條式子換一組區域參數，答案差一倍以上。那條 1989 年的式子到今天
# 仍是多國作業系統的骨幹。本章不重推它，只問一件事：**把它接上
# 電源、讓它每天對外講話，還缺什麼**？
#
# 答案不太符合理工科的直覺。缺的不是更好的概似函數，而是：資料在
# 深夜三點壞掉時誰值班、機率算出來由誰簽名發布、5% 這個數字要用
# 什麼句型說給一個剛失去房子的人聽、以及當模型根本不存在時該怎麼
# 辦。這一章的主角因此有三個：**STEP**（Gerstenberger et al. 2005,
# *Nature*）這個把「明天的地震」變成即時地圖的原型系統、三個國家
# 二十年來長出的三種制度，以及一門有假說、有實驗、有可測量結果的
# 科學——機率溝通。
#
# ## 22.1 從模型到系統的七步
#
# 先把整條路徑攤開。從一份地震目錄到一個能支撐工程決策的系統，中
# 間有七個台階，每一階都會冒出前一階沒有的問題：
#
# | 步 | 這一步在做什麼 | 新冒出來的需求 |
# |---|---|---|
# | 1 經驗律 | Omori–Utsu、GR | 一份目錄 |
# | 2 模型 | R–J、ETAS、STEP、EEPAS | 參數估計、$M_c$、要不要模擬 |
# | 3 檢驗 | CSEP、前瞻、基準比較 | **一個社群**（第三方） |
# | 4 系統 | 自動化、近即時、與國家危害模型整合 | 工程、機房、成本取捨 |
# | 5 權威 | 誰有法定責任發布 | **制度** |
# | 6 溝通 | 說給誰、怎麼說、多久一次 | 社會科學、共同設計 |
# | 7 風險 | OELF、時變危害、補強政策 | 曝險與易損性資料 |
#
# 這張表的重點不在七這個數字，而在**第 3 步之後的斷層**。第 1、2
# 步是統計問題，可以一個人在筆電上做完。第 3 步開始需要別人——
# 因為「開發者自己相信自己的模型」在這個領域裡不構成證據
# （{doc}`第 9 章 <09_forecasting_intro>`的 CSEP 三條紀律，工具箱
# 在{doc}`第 18 章 <18_testing_comparison>`）。而從第 4 步起，**瓶頸
# 就不再是統計**：義大利有全世界最完整的作業化系統，卻至今不對
# 大眾公開；紐西蘭因為 2012 年換了定位系統，模型參數到現在還卡在
# 換系統之前。這些都不是概似函數能解決的問題。
#
# 學生最容易誤判的也正是這裡：以為「把模型做得更準」是唯一的進步
# 方向。本章接下來的每一節，都是這個誤判的反例。
#
# 順帶把一個非常容易混淆的時間軸釘住。**地震預警（EEW）**是
# 「破裂已經發生、地震波還在路上」的**真即時**問題——秒的尺度，
# 拚的是通訊比 S 波快。本章的 OEF 則是「破裂**尚未**發生」的
# **近即時**問題——分鐘到天的尺度，「近」這個字誠實承認了不可
# 避免的處理延遲：目錄要更新、參數要重估、機率要算、還要有人
# 看過才發得出去。兩者的輸入、輸出、使用者與失敗模式全都不同，
# 唯一的共同點是都得在半夜自動運轉。
#
# ## 22.2 STEP 的架構
#
# STEP（Short-Term Earthquake Probability）2005 年在加州上線，是
# 第一個把即時餘震預報鋪成**空間地圖**的系統。它要補的兩個洞，
# *Nature* 摘要親口點名：既有的通用短期叢集模型**不針對眼前這個
# 序列調校**，而且**不含餘震會發生在哪裡的資訊**。
#
# ### 三個複雜度遞增的元素
#
# STEP 與 R–J、ETAS 的物理內核相同（疊加的 Omori 序列，每個地震
# 都能生自己的餘震），但架構不同：它不是一個自洽的單一模型，而是
# **數個可以各自獨立視為模型的元件之組合**。時變的部分有三個元件，
# 複雜度遞增，切換由**資料量**決定：
#
# 1. **資料不足時**（序列剛開始，手上只有主震）：直接套用由過去
#    地震活動導出的**區域通用參數**。空間上先以主震為中心給一個
#    隨距離遞減的圓形餘震區，等真的有餘震進來，再據以估計斷層跡、
#    修正餘震分布的形狀。
# 2. **當序列累積到完整規模以上至少 100 個餘震**：改用**該序列
#    自己擬合**的參數。注意重新擬合會連帶改變整個序列的 $b$ 值，
#    不只是 Omori 那幾個參數。
# 3. **當序列的生產力足夠高**（大到每個子區都還有足夠事件可擬合）：
#    參數進一步**容許在空間上變化**，序列的不同段落各有各的行為。
#
# 三個元件依各自**對觀測資料的擬合程度**，以 AIC 加權合併
# （Steacy et al. 2014 對 STEP 的描述即為此）。這裡只講觀念不寫
# 公式：**資料少時通用元件主導，資料累積後序列自身的行為接手**。
# 把這個切換畫成示意圖：
#
# （三個元件的中文名稱是依其觸發條件描述，不是原論文的標籤。）

